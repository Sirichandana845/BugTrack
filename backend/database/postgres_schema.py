"""PostgreSQL schema for BugTrack."""

POSTGRES_SCHEMA = [
    """
    CREATE TABLE IF NOT EXISTS users (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        email TEXT NOT NULL UNIQUE,
        password_hash TEXT NOT NULL,
        role TEXT NOT NULL CHECK (
            role IN ('admin', 'developer', 'tester', 'reporter')
        ),
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
    """,

    """
    CREATE TABLE IF NOT EXISTS bugs (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        title TEXT NOT NULL,
        description TEXT,
        module TEXT,
        steps_to_reproduce TEXT,
        expected_result TEXT,
        actual_result TEXT,
        severity TEXT NOT NULL DEFAULT 'Medium',
        impact TEXT NOT NULL DEFAULT 'Medium',
        recommended_priority TEXT,
        priority TEXT,
        status TEXT NOT NULL DEFAULT 'reported',
        assigned_to BIGINT REFERENCES users(id) ON DELETE SET NULL,
        created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
        resolution TEXT,
        attachment TEXT,
        operating_system TEXT,
        browser_device TEXT,
        app_version TEXT,
        fix_description TEXT,
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
    """,

    """
    CREATE TABLE IF NOT EXISTS bug_history (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        bug_id BIGINT NOT NULL REFERENCES bugs(id) ON DELETE CASCADE,
        user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
        action TEXT NOT NULL,
        old_value TEXT,
        new_value TEXT,
        note TEXT,
        timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
    """,

    """
    CREATE TABLE IF NOT EXISTS comments (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        bug_id BIGINT NOT NULL REFERENCES bugs(id) ON DELETE CASCADE,
        user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
        comment TEXT NOT NULL,
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
    """,

    """
    CREATE TABLE IF NOT EXISTS notifications (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        title TEXT NOT NULL,
        message TEXT NOT NULL,
        bug_id BIGINT REFERENCES bugs(id) ON DELETE CASCADE,
        type TEXT NOT NULL DEFAULT 'info',
        is_read INTEGER NOT NULL DEFAULT 0,
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
    """,

    """
    CREATE TABLE IF NOT EXISTS password_resets (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        email TEXT NOT NULL,
        token TEXT NOT NULL UNIQUE,
        expires_at TIMESTAMP NOT NULL,
        used INTEGER NOT NULL DEFAULT 0,
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
    """,

    "CREATE INDEX IF NOT EXISTS idx_bugs_status ON bugs(status)",
    "CREATE INDEX IF NOT EXISTS idx_bugs_module ON bugs(module)",
    "CREATE INDEX IF NOT EXISTS idx_bugs_assigned ON bugs(assigned_to)",
    "CREATE INDEX IF NOT EXISTS idx_bugs_creator ON bugs(created_by)",
    "CREATE INDEX IF NOT EXISTS idx_history_bug ON bug_history(bug_id)",
    "CREATE INDEX IF NOT EXISTS idx_comments_bug ON comments(bug_id)",
    "CREATE INDEX IF NOT EXISTS idx_notifications_user ON notifications(user_id, is_read)",
    "CREATE INDEX IF NOT EXISTS idx_resets_token ON password_resets(token)",
]